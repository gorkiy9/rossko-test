function scrollToSection(id: SectionId) {
  const el = document.getElementById(id)
  if (!el) return
  const reduce = window.matchMedia('(prefers-reduced-motion: reduce)').matches
  el.scrollIntoView({ behavior: reduce ? 'auto' : 'smooth', block: 'start' })
}

function Section({ id, children }: { id: SectionId; children: ReactNode }) {
  const title = SECTIONS.find((s) => s.id === id)!.title
  return (
    <section id={id} className="r-card p-section" aria-labelledby={`${id}-title`}>
      <h2 id={`${id}-title`} className="p-h2">
        {title}
      </h2>
      {children}
    </section>
  )
}

function Callout({
  icon,
  title,
  tone = 'accent',
  children,
}: {
  icon: IconName
  title: string
  tone?: 'accent' | 'muted'
  children: ReactNode
}) {
  return (
    <div className={`p-callout p-callout--${tone}`}>
      <Icon name={icon} size={20} />
      <p>
        <b>{title}.</b> {children}
      </p>
    </div>
  )
}

/** Таблица с горизонтальной прокруткой на узком экране. keyCol — первая колонка как подпись строки */
function Table({ head, rows, keyCol }: { head: string[]; rows: ReactNode[][]; keyCol?: boolean }) {
  return (
    <div className="p-table" role="region" aria-label={head.join(', ')} tabIndex={0}>
      <table>
        <thead>
          <tr>
            {head.map((h) => (
              <th key={h} scope="col">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={i}>
              {r.map((c, j) =>
                j === 0 && keyCol ? (
                  <th key={j} scope="row">
                    {c}
                  </th>
                ) : (
                  <td key={j}>{c}</td>
                ),
              )}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

